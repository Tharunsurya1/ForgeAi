def test_artifact_draft_model_and_size():
    """Test ArtifactDraft properties, encoding, and UTF-8 size calculation."""
    content = "SELECT * FROM users;\n-- Unicode check: 🚀 ⚡"
    artifact = ArtifactDraft(
        artifact_type="erd",
        file_path="schema.sql",
        content=content,
        language="sql",
    )

    assert artifact.artifact_type == "erd"
    assert artifact.file_path == "schema.sql"
    assert artifact.language == "sql"
    assert artifact.file_size_bytes == len(content.encode("utf-8"))


