def test_agent_valid_input_and_execution():
    """Test successful agent run with valid input and output schema validation."""
    agent = DummySpecialistAgent()
    context = AgentContext(
        workflow_id="wf-123",
        project_id="proj-456",
        prompt="Build an enterprise CRM platform",
        tech_stack={"backend": "FastAPI", "database": "PostgreSQL"},
    )

    result = agent.run(context)

    assert result.success is True
    assert result.agent_name == "DummySpecialistAgent"
    assert result.version == "1.0.0"
    assert result.error is None
    assert result.data["score"] == 95
    assert "Processed: Build an enterprise" in result.data["summary"]
    assert len(result.artifacts) == 1
    assert result.execution_time_ms >= 0


def test_agent_invalid_input_validation():
    """Test that input failing schema constraints produces a structured failure."""
    agent = DummySpecialistAgent()
    # Prompt is too short (< 5 chars), violating SampleInputSchema
    context = AgentContext(
        workflow_id="wf-123",
        project_id="proj-456",
        prompt="Hi",
    )

    result = agent.run(context)

    assert result.success is False
    assert result.error is not None
    assert "Input validation failed" in result.error
    assert result.error_details["error_code"] == "INVALID_AGENT_INPUT"
    assert result.error_details["stage"] == "input_validation"
    assert result.error_details["retryable"] is False
    assert len(result.artifacts) == 0


