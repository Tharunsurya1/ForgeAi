def test_payload_sanitizer():
    """Test that sensitive credentials, tokens, and keys are redacted from payloads."""
    raw_payload = {
        "user_email": "developer@forgeai.com",
        "api_key": "sk-live-1234567890",
        "nested": {
            "token": "bearer-jwt-token-val",
            "password": "SecretPassword123!",
            "public_id": "pub_999",
        },
        "items": [
            {"access_token": "secret_access", "name": "Item A"},
            {"secret": "top_secret_value", "safe_field": 42},
        ],
    }

    sanitized = sanitize_payload(raw_payload)

    assert sanitized["user_email"] == "developer@forgeai.com"
    assert sanitized["api_key"] == "[REDACTED]"
    assert sanitized["nested"]["token"] == "[REDACTED]"
    assert sanitized["nested"]["password"] == "[REDACTED]"
    assert sanitized["nested"]["public_id"] == "pub_999"
    assert sanitized["items"][0]["access_token"] == "[REDACTED]"
    assert sanitized["items"][0]["name"] == "Item A"
    assert sanitized["items"][1]["secret"] == "[REDACTED]"
    assert sanitized["items"][1]["safe_field"] == 42
