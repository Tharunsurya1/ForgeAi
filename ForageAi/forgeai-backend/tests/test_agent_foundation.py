# ---------------------------------------------------------------------------
# Test Schemas and Dummy Agent Implementation
# ---------------------------------------------------------------------------

class SampleInputSchema(BaseModel):
    prompt: str = Field(..., min_length=5)
    tech_stack: Dict[str, Any] = Field(default_factory=dict)
    shared_state: Dict[str, Any] = Field(default_factory=dict)
    metadata: Dict[str, Any] = Field(default_factory=dict)


class SampleOutputSchema(BaseModel):
    summary: str = Field(..., min_length=3)
    score: int = Field(..., ge=0, le=100)


class DummySpecialistAgent(BaseAgent):
    agent_name = "DummySpecialistAgent"
    version = "1.0.0"
    description = "Test agent for foundation validation"
    input_schema = SampleInputSchema
    output_schema = SampleOutputSchema

    def execute(
        self,
        context: AgentContext,
        validated_input: Dict[str, Any],
    ) -> Tuple[Dict[str, Any], List[ArtifactDraft]]:
        # Check special trigger prompts for testing different failure paths
        prompt = validated_input["prompt"]

        if "trigger_unhandled" in prompt:
            raise RuntimeError("Simulated unexpected crash")

        if "trigger_bad_output" in prompt:
            # Score out of bounds (< 0) to trigger output_validation error
            return {"summary": "Bad", "score": -10}, []

        if "trigger_domain_error" in prompt:
            raise AgentExecutionError(
                message="Domain rule violation",
                agent_name=self.agent_name,
                error_code="RULE_VIOLATION",
                stage="execution",
                details={"reason": "simulated_violation"},
                retryable=True,
            )

        artifacts = [
            ArtifactDraft(
                artifact_type="requirements",
                file_path="docs/SPEC.md",
                content=f"# Specifications for {prompt}\nGenerated successfully.",
                language="markdown",
                metadata={"test": True},
            )
        ]
        return {"summary": f"Processed: {prompt[:20]}", "score": 95}, artifacts


